def t(key, lang='ar', **kwargs):
    """Translate a key. Falls back to the English text, then to the key."""
    entry = KEYS.get(key)
    if entry is None:
        return key
    text = entry[1] if lang == 'en' else entry[0]
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def has(key):
    return key in KEYS


def lang_of(value):
    return 'en' if (value or '').lower().startswith('en') else 'ar'


